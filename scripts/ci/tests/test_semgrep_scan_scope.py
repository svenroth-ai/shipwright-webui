def test_scan_scope_patterns_match_the_pinned_set() -> None:
    """Both directions: disk -> registry and registry -> disk.

    Cannot pass vacuously: an empty or unreadable `.semgrepignore` leaves every
    pinned pattern in the `stale` set below and fails there.
    """
    live = set(live_patterns())
    pinned = set(_SCOPE_PATTERNS)

    unregistered = sorted(live - pinned)
    assert not unregistered, (
        f"these .semgrepignore patterns are live but not pinned: {unregistered}.\n"
        "Each one removes a subtree from the security scan permanently, with no "
        "expiry and nothing else able to see it. Add an entry to _SCOPE_PATTERNS "
        "explaining why the excluded files are NOT shipped. If the goal is to "
        "silence a REACHABLE finding, this is the wrong channel — that is a risk "
        "acceptance and belongs in shipwright_accepted_risks.yaml."
    )
    stale = sorted(pinned - live)
    assert not stale, (
        f"these patterns are pinned here but no longer in .semgrepignore: {stale}.\n"
        "Remove the entry in the same change, or this registry starts describing "
        "a scan scope that does not exist."
    )


def test_every_scan_scope_pattern_carries_a_rationale() -> None:
    thin = sorted(
        pattern
        for pattern, rationale in _SCOPE_PATTERNS.items()
        if len(rationale.strip()) < MIN_RATIONALE
    )
    assert not thin, (
        f"these scope patterns have no usable rationale: {thin}.\n"
        "A pinned list alone buys drift control, not governance. Say why the "
        "excluded files are not shipped, or point at the decision that says so."
    )


def test_the_build_shaping_script_is_in_scan_scope() -> None:
    """`server/scripts/` was excluded wholesale; one file in it ships.

    `server/package.json` runs `"build": "tsc && node scripts/copy-assets.mjs"`,
    and that script copies `src/config` -> `dist/config`. Without it
    `node dist/index.js` ENOENTs on `dist/config/default-actions.json` — which is
    exactly why `server/src/test/build-assets.test.ts` exists. It shapes the
    SHIPPED artifact, so the blanket exclusion was excluding production code, not
    a dev script. Found by the Codex cross-check on trg-ab54e3d1.
    """
    patterns = live_patterns()
    assert "server/scripts/" not in patterns, (
        "`server/scripts/` is back as a blanket exclusion. That directory is not "
        "purely non-production: copy-assets.mjs is wired into the server build "
        "and decides what lands in dist/. Exclude the non-shipped files by name."
    )
    assert not excluded("server/scripts/copy-assets.mjs", patterns), (
        "server/scripts/copy-assets.mjs is excluded from the security scan, but "
        "`server/package.json` runs it as the second half of `npm run build`. "
        "Production code must stay in scope."
    )
    for rel in (
        "server/scripts/sdk-poc.ts",
        "server/scripts/regen-triage-fixtures.py",
        "server/scripts/regen-launch-payload-fixtures.py",
    ):
        assert excluded(rel, patterns), (
            f"{rel} is no longer excluded from the scan. If that is intentional, "
            "drop its _SCOPE_PATTERNS entry in the same change; if not, restore "
            "the pattern."
        )
