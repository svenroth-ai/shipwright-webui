"""RATCHET over the Semgrep scan-SCOPE channel — `.semgrepignore`.

One of two channels this repo uses that `accepted_risks_cli.py check` cannot
see. CLAUDE.md DO-NOT #25 says the register gate covers THREE channels (a
`.trivyignore.yaml` id and the two `SHIPWRIGHT_SEMGREP_*` keys in security.yml)
and names what stays open; this is the largest of those, because one line here
silences an entire subtree, permanently, with no expiry.

WHY A RATCHET AND NOT REGISTER ENTRIES. Decided after a Codex cross-check
(triage trg-ab54e3d1) and deliberately not reopened. This list is a scan-SCOPE
definition, not a risk acceptance: it excludes artifacts that are not shipped,
exactly as `.github/codeql/codeql-config.yml` already does under its own
recorded decision, and the register's own header forbids using it to silence
REACHABLE findings. Registering these would create perpetual-renewal entries
with no security value.

So the set is pinned exactly, both directions, and every entry carries a
rationale — a bare pinned list buys drift control and not governance (the
cross-check's caveat, accepted). Adding an exclusion now fails CI until the
justification is written, which is the moment it is answerable.

Sibling: `test_semgrep_inline_suppressions.py` (the per-site channel). Shared
discovery: `semgrep_channels.py`. Scanner regression tests:
`test_semgrep_channels_scanner.py`.
"""

